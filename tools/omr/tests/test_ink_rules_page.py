"""The rule page (`docs/ink-rules.md`, ROADMAP 2.207) cannot silently go stale.

The page is GENERATED by `benchmarks/rule-page/build_rule_page.py`: the list of rules is read out of the code
(`adjudicate.REGISTRY` and each decision's declared reasons, `evaluate.RULES`, `infer.RULES`, the staged/ module
files) and only the meaning and kind of each rule is hand-kept (`benchmarks/rule-page/rule_kinds.py`).  These
tests fail when

  * the code declares a reason / rule / module the committed page does not mention;
  * `rule_kinds.py` names a rule the code no longer has;
  * the committed page differs from a fresh build (someone edited it by hand, or changed the code and did not
    run `build_rule_page.py --write`);
  * a kind is not one of the known letters.

CONTROL THAT CAN FAIL: `test_the_check_can_fail` deletes one reason from the page text and requires the checker
to flag exactly that reason -- a check that cannot fail is not a control (CLAUDE rule 7).
"""
from __future__ import annotations

import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
RULE_DIR = ROOT / "benchmarks" / "rule-page"
PAGE = ROOT / "docs" / "ink-rules.md"


def _builder():
    sys.path.insert(0, str(RULE_DIR))
    spec = importlib.util.spec_from_file_location("build_rule_page", RULE_DIR / "build_rule_page.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


B = _builder()
K = B.K
INV = B.code_inventory()


def missing_from_page(text, inv=INV):
    """Everything the code emits that no line of the page names, as readable strings."""
    lines = text.splitlines()
    out = []
    for d in inv["decisions"]:
        for r in d["reasons"]:
            if r == K.STUB_REASON:
                continue
            if not any(f"`{d['name']}`" in ln and f"`{r}`" in ln for ln in lines):
                out.append(f"decision {d['name']} reason {r}")
    for e in inv["evaluate"]:
        if not any(f"| {e['name']} |" in ln and "EVALUATE" in ln for ln in lines):
            out.append(f"EVALUATE rule {e['name']}")
    for i in inv["infer"]:
        if not any(f"| {i['name']} |" in ln and "INFER" in ln for ln in lines):
            out.append(f"INFER rule {i['name']}")
    for name in K.PASSES:
        if not any(f"| {name} |" in ln for ln in lines):
            out.append(f"post-pass {name}")
    registered = {d["module"] for d in inv["decisions"]}
    for f in inv["files"]:
        base = f.split("/")[-1]
        if base[:-3] in registered or base in K.INFRA:
            continue
        if not any(f"`{f}`" in ln for ln in lines):
            out.append(f"module {f}")
    return out


def test_the_page_exists():
    assert PAGE.is_file(), "docs/ink-rules.md missing: run python3 benchmarks/rule-page/build_rule_page.py --write"


def test_every_reason_rule_and_module_the_code_emits_is_on_the_page():
    missing = missing_from_page(PAGE.read_text())
    assert not missing, ("the code emits rules the page does not name; run "
                         "`python3 benchmarks/rule-page/build_rule_page.py --write`: " + "; ".join(missing[:20]))


def test_the_check_can_fail():
    text = PAGE.read_text()
    d = next(x for x in INV["decisions"] if x["name"] == "adjudicate_duration")
    victim = "owned_by_another_staff"
    assert victim in d["reasons"]
    mutated = "\n".join(ln.replace(f"`{victim}`", "`x`") if f"`{d['name']}`" in ln else ln for ln in text.splitlines())
    assert missing_from_page(mutated) == [f"decision adjudicate_duration reason {victim}"]
    assert missing_from_page(text.replace("`adjudicators/key_slots.py`", "`x`")) == ["module adjudicators/key_slots.py"]


def test_rule_kinds_names_nothing_the_code_no_longer_has():
    _text, stale = B.render()
    assert not stale, f"rule_kinds.py names reasons the code no longer declares: {stale}"
    assert set(K.EVALUATE_RULES) == {e["name"] for e in INV["evaluate"]}
    assert set(K.INFER_RULES) == {i["name"] for i in INV["infer"]}
    present = set(INV["files"])
    for f in K.MODULES:
        assert f in present, f"rule_kinds.MODULES names a file that is gone: {f}"
    for f in K.INFRA:
        assert f in present, f"rule_kinds.INFRA names a file that is gone: {f}"


def test_the_committed_page_is_a_fresh_build():
    text, _stale = B.render()
    assert PAGE.read_text() == text, "docs/ink-rules.md differs from a fresh build: run build_rule_page.py --write"


def test_every_kind_is_a_known_kind():
    ok = ("A", "B", "C", "D", "U", "ok")
    for e in K.RULES:
        assert e.kind.split(":")[0] in ok, e
    for table in (K.EVALUATE_RULES, K.INFER_RULES, K.PASSES, K.MODULES):
        for name, t in table.items():
            assert t[1].split(":")[0] in ok, (name, t)


def test_the_fire_tables_are_the_two_acceptance_movements():
    import json
    for tag in ("litolff", "brahms"):
        d = json.load(open(RULE_DIR / f"fires-{tag}.json"))
        assert d["verdicts_total"] > 100000 and d["rows"], tag
