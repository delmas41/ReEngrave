def _built():
    return FM.build()


class TestThePageIsCurrent(unittest.TestCase):
    def test_the_committed_page_is_a_fresh_build(self):
        text = FM.render(_built())
        self.assertTrue(FM.PAGE.is_file(), "docs/data-flow.md missing: run python3 -m tools.omr.staged.flow_map")
        self.assertEqual(FM.PAGE.read_text(), text, "docs/data-flow.md is stale: run python3 -m tools.omr.staged.flow_map")

    def test_the_declared_table_agrees_with_the_code(self):
        self.assertEqual(_built().problems, [])

    def test_every_mark_has_a_block_and_every_fact_has_a_block(self):
        text = FM.render(_built())
        for m in FM.MARKS:
            self.assertIn(f"### {m.name} -- `--mark {m.key}`", text)
        for q in _built().an.q_vals:
            self.assertIn(f"### `{q}` (Q.", text)


class TestTheQueriesPrintThePagesOwnRows(unittest.TestCase):
    def _run(self, *argv):
        buf = io.StringIO()
        with redirect_stdout(buf):
            rc = FM.main(list(argv))
        return rc, buf.getvalue().splitlines()

    def test_mark_quantity_and_consumer(self):
        page = FM.render(_built()).splitlines()
        rc, lines = self._run("--mark", "clef")
        self.assertEqual(rc, 0)
        self.assertTrue(lines and lines[0].startswith("### Clef"))
        i = page.index(lines[0])
        self.assertEqual(page[i:i + len(lines)], lines)
        rc, lines = self._run("--quantity", "Q.CLEF")
        self.assertEqual(rc, 0)
        i = page.index(lines[0])
        self.assertEqual(page[i:i + len(lines)], lines)
        rc, lines = self._run("--consumer", "export.py:_clef_changes_by_bar")
        self.assertTrue(lines)
        for ln in lines:
            self.assertIn(ln, page)


class TestTheTableCannotRot(unittest.TestCase):
    def test_CONTROL_a_mark_naming_a_gone_function_fails(self):
        an = _built().an
        bad = FM.Mark("x", "X", "x", {"gather.py:no_such_reader": "ink"}, ("no_such_decision",))
        with mock.patch.object(FM, "MARKS", FM.MARKS + (bad,)):
            probs = FM.table_problems(an)
        self.assertTrue(any("no_such_reader" in p for p in probs), probs)
        self.assertTrue(any("no_such_decision" in p for p in probs), probs)

    def test_CONTROL_a_reader_no_mark_lists_fails(self):
        an = _built().an
        marks = tuple(FM.Mark(m.key, m.name, m.plain, {k: v for k, v in m.readers.items() if k != "gather.py:gather_clef_pagewide"},
                              m.deciders, m.claims, m.old, m.written, m.new) for m in FM.MARKS)
        with mock.patch.object(FM, "MARKS", marks):
            probs = FM.table_problems(an)
        self.assertIn("a GATHER function files rows and is in no mark: gather.py:gather_clef_pagewide (add it to `flow_map.MARKS`)", probs)


_TREE = {
    "gather.py": '''
        import os
        from .record import Q

        def extra_enabled():
            return os.environ.get("OMR_TEST_EXTRA", "") == "1"

        def on_enabled():
            return os.environ.get("OMR_TEST_ON", "1") != "0"

        def gather_a(log, s):
            log.observe(s, Q.A, 1, reader="r", frame="f")

        def gather_c(log, s):
            if not extra_enabled():
                return
            log.observe(s, Q.C, 1, reader="r", frame="f")

        def gather_d(log, s):
            if on_enabled():
                log.observe(s, Q.D, 1, reader="r", frame="f")

        def gather(log, s):
            gather_a(log, s)
            gather_c(log, s)
            gather_d(log, s)
            log.abstain(s, Q.B, reader="r", frame="f", reason="no_ink_here")
    ''',
    "adjudicators/x.py": '''
        from ..record import Q

        def decide(ev, s):
            a = ev.rows(Q.A, s)
            b = ev.rows(Q.B, s)
            c = ev.rows(Q.C, s)
            d = ev.rows(Q.D, s)
            return Ruling.abstain("other_word")

        def consumer(v):
            if v.reason == "gone_word":
                return 1
            if v.reason == "other_word":
                return 2
            return 0
    ''',
    "record.py": "class Q:\n    A = 'a'\n    B = 'b'\n    C = 'c'\n    D = 'd'\n",
}


class TestTheCheckCatchesAPlantedGap(unittest.TestCase):
    """The control: a planted read-without-producer, a planted read-behind-an-off-flag and a planted dead reason word are each caught; the
    filed fact, the fact behind an ON flag and the returned reason word are not."""

    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        root = pathlib.Path(cls.tmp.name) / "staged"
        for rel, body in _TREE.items():
            p = root / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(textwrap.dedent(body))
        (root / "adjudicators" / "__init__.py").write_text("")
        cls.an = FM.Analysis(root=root, q_values={"A": "a", "B": "b", "C": "c", "D": "d"}, registry=False,
                             stage_of_file={"gather.py": "GATHER"}, not_a_stage={"record.py"})

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_CONTROL_read_without_a_producer_and_behind_an_off_flag(self):
        got = {r["quantity"]: r["status"] for r in R.live_producers(self.an)}
        self.assertEqual(got, {"b": FM.READ_NEVER_FILED, "c": FM.OFF_FLAG})

    def test_CONTROL_dead_reason_word(self):
        got = {r["word"] for r in R.reason_words(self.an)}
        self.assertEqual(got, {"gone_word"})

    def test_the_off_flag_is_read_off_the_code(self):
        preds = {p.name: p.default for p in self.an.predicates()}
        self.assertEqual(preds, {"extra_enabled": False, "on_enabled": True})


