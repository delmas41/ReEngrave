"""ROADMAP 2.331 step 3: the generated data-flow map (`docs/data-flow.md`) and the tightened check.

The page is GENERATED by `python3 -m tools.omr.staged.flow_map` from the code. These tests fail when

  * the committed page differs from a fresh build (the code changed and nobody ran the generator, or the page was edited by hand);
  * the one declared table (`flow_map.MARKS`) names a reader or a decision the code no longer has, or the code has a reader no mark lists;
  * the query commands (`--mark`, `--quantity`, `--consumer`) print rows that are not the page's own rows.

CONTROLS THAT CAN FAIL (CLAUDE rule 7): a throwaway staged tree with a fact READ and filed by nothing, a fact read and filed only behind a
default-off flag, and a reason word tested that no decider returns -- the check must name all three, and must NOT name the fact that is filed,
the reason word that is returned, or the flag that is on. And a table that names a function that is gone must fail the build.
"""
from __future__ import annotations

