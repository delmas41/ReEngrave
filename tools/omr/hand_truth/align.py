import hashlib
import json
import shutil
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from tools.omr.hand_truth.store import REPO

SCHEMA = "reengrave-hand-truth-aligned/1"
PAGES_DIR = REPO / "data" / "hand-truth" / "pages"
ALIGNED_DIR = REPO / "data" / "hand-truth" / "aligned"
Rect = Tuple[float, float, float, float]


class AlignError(RuntimeError):
    """An alignment that cannot be made or trusted. Never swallowed."""


# ───────────────────────────── 1. reading the two sides ─────────────────────────────

def _cm():
    from tools.omr.staged import cell_map as CM
    return CM


def default_root() -> Path:
    return _cm().ROOT_DEFAULT


def label_pages(pages_dir: Path = PAGES_DIR) -> List[Path]:
    """Every hand-truth page file (`<edition>/<n>.json`; the `.review.json` marks are not pages)."""
    out = []
    for p in sorted(Path(pages_dir).glob("*/*.json")):
        if p.name.endswith(".review.json") or not p.stem.isdigit():
            continue
        out.append(p)
    return out


def find_master(root: Any, pdf_name: str, page: int) -> Optional[Path]:
    """The master directory under `root` cut from the pdf called `pdf_name` that holds `page`, or None."""
    root = Path(root)
    if not root.is_dir():
        return None
    for d in sorted(root.iterdir()):
        mf = d / "manifest.json"
        if not mf.exists():
            continue
        try:
            man = json.loads(mf.read_text())
        except (OSError, ValueError):
            continue
        if man.get("pdf_name") == pdf_name and str(page) in (man.get("pages") or {}):
            return d
    return None


def labels_digest(page: Dict[str, Any]) -> str:
    """What an alignment depends on in Sean's page: every box's id, rect and cell id, every cell's id, kind, rect and
    staff lines. A label edited in the UI changes this and makes the aligned file stale."""
    body = {
        "boxes": sorted([b["id"], [round(float(v), 3) for v in b["rect"]], b.get("cell_id")] for b in page["boxes"]),
        "cells": sorted([c["id"], c["kind"], [round(float(v), 3) for v in c["rect"]], c.get("system"), c.get("staff"),
                         c.get("measure"), [round(float(v), 2) for v in (c.get("staff_line_ys") or [])]]
                        for c in page["cells"]),
        "dpi": page.get("dpi"),
    }
    return hashlib.sha256(json.dumps(body, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def _master_cells(mdir: Path, page: int) -> Tuple[Dict[str, Any], List[Dict[str, Any]], Dict[str, Any]]:
    """(snapshot, [cell rows], barline columns by system). A cell row: id (session spelling, page-wide staff), key
    (the record's `cell/p/s/st/c`), system, staff (local), page_staff, cell, rect, line_ys, middle."""
    CM = _cm()
    snap = CM.read_page(mdir, page)
    staves = [CM.dec(s) for s in snap["staves"]]
    loc = CM._local_map(staves)
    mid = {s["staff_index"]: (float(s["line_ys"][0]) + float(s["line_ys"][-1])) / 2.0 for s in staves}
    rows = []
    for c in snap["cells"]:
        v = CM.dec(c["v"])
        s, st = loc.get(v["staff_index"], (v["system_index"], v["staff_index"]))
        rows.append({
            "id": "s%d-st%d-m%d" % (v["system_index"], v["staff_index"], v["measure_index"]),
            "key": "cell/%d/%d/%d/%d" % (page, s, st, v["measure_index"]),
            "system": int(s), "staff": int(st), "page_staff": int(v["staff_index"]), "cell": int(v["measure_index"]),
            "rect": [float(x) for x in v["bbox_page_px"]],
            "line_ys": [round(float(y), 2) for y in v["staff_line_ys_canonical"]],
            "middle": mid.get(v["staff_index"], 0.0),
        })
    cols: Dict[str, List[int]] = {}
    for b in snap["barlines"]:
        b = CM.dec(b)
        cols.setdefault(str(b["system_index"]), []).append(int(b["x"]))
    return snap, rows, {k: sorted(v) for k, v in cols.items()}


def _holds(rect: Sequence[float], cx: float, cy: float) -> bool:
    return rect[0] <= cx < rect[2] and rect[1] <= cy < rect[3]


# ───────────────────────────── 2. the alignment ─────────────────────────────

def _frame(page: Dict[str, Any], mrows: List[Dict[str, Any]], mcols: Dict[str, List[int]]) -> Dict[str, Any]:
    """The label's cell frame against the master's: cells by session id, line ys, and the x edges (barline columns)
    each system's cells were cut at."""
    mine = {c["id"]: c for c in page["cells"] if c["kind"] == "measure"}
    master = {r["id"]: r for r in mrows}
    rect_changed, ys_changed = [], []
    for k in sorted(set(mine) & set(master)):
        a, b = mine[k], master[k]
        if [round(float(v)) for v in a["rect"]] != [round(v) for v in b["rect"]]:
            rect_changed.append({"cell": k, "label": [round(float(v), 1) for v in a["rect"]], "master": b["rect"]})
        elif [round(float(v), 1) for v in (a.get("staff_line_ys") or [])] != [round(v, 1) for v in b["line_ys"]]:
            ys_changed.append(k)
    edges_l: Dict[str, set] = {}
    for c in mine.values():
        edges_l.setdefault(str(c["system"]), set()).update((round(float(c["rect"][0])), round(float(c["rect"][2]))))
    edges_m: Dict[str, set] = {}
    for r in mrows:
        edges_m.setdefault(str(r["system"]), set()).update((round(r["rect"][0]), round(r["rect"][2])))
    edge_diff = {}
    for s in sorted(set(edges_l) | set(edges_m), key=int):
        a, b = edges_l.get(s, set()), edges_m.get(s, set())
        if a != b:
            edge_diff[s] = {"only_in_labels": sorted(a - b), "only_in_master": sorted(b - a)}
    staves_l = {(c["system"], c["staff"]) for c in mine.values()}
    staves_m = {(r["system"], r["page_staff"]) for r in mrows}
    kinds: Dict[str, int] = {}
    for c in page["cells"]:
        if c["kind"] != "measure":
            kinds[c["kind"]] = kinds.get(c["kind"], 0) + 1
    return {
        "measure_cells": {"labels": len(mine), "master": len(master), "same": len(set(mine) & set(master))
                          - len(rect_changed) - len(ys_changed),
                          "rect_changed": rect_changed, "line_ys_changed": ys_changed,
                          "only_in_labels": sorted(set(mine) - set(master)),
                          "only_in_master": sorted(set(master) - set(mine))},
        "staves": {"labels": len(staves_l), "master": len(staves_m),
                   "only_in_labels": sorted(staves_l - staves_m), "only_in_master": sorted(staves_m - staves_l)},
        "cell_x_edges_differing_by_system": edge_diff,
        "master_barline_columns": mcols,
        "label_only_cells_by_kind": dict(sorted(kinds.items())),
    }


def build_alignment(page_path: Path, mdir: Path) -> Dict[str, Any]:
    """The alignment of one hand-truth page to one master directory, as a JSON value."""
    page = json.loads(Path(page_path).read_text())
    pi = int(page["pdf_page_index"])
    man = _cm().read_manifest(Path(mdir))
    if str(pi) not in man["pages"]:
        raise AlignError("master %s has no page %d" % (mdir, pi))
    if int(man["dpi"]) != int(page["dpi"]):
        raise AlignError("master %s was cut at %s dpi, the labels at %s" % (mdir, man["dpi"], page["dpi"]))
    snap, mrows, mcols = _master_cells(Path(mdir), pi)
    by_id = {r["id"]: r for r in mrows}
    label_cells = {c["id"]: c for c in page["cells"]}
    boxes: Dict[str, Any] = {}
    why_count: Dict[str, int] = {}
    n_agree = 0
    for b in page["boxes"]:
        r = [float(v) for v in b["rect"]]
        cx, cy = (r[0] + r[2]) / 2.0, (r[1] + r[3]) / 2.0
        old = b.get("cell_id")
        held = [m for m in mrows if _holds(m["rect"], cx, cy)]
        pick = next((m for m in held if m["id"] == old), None) \
            or (min(held, key=lambda m: abs(m["middle"] - cy)) if held else None)
        lc = label_cells.get(old)
        row: Dict[str, Any] = {"old": old, "master": pick["key"] if pick else None,
                               "master_id": pick["id"] if pick else None}
        if pick is not None and pick["id"] == old:
            row["ok"] = True
            n_agree += 1
            if len(held) > 1:
                row["also_in"] = sorted(m["id"] for m in held if m["id"] != old)
        else:
            row["ok"] = False
            if lc is None:
                why = "old-cell-not-on-page"
            elif lc["kind"] != "measure":
                why = "label-only-cell"
            elif _holds(lc["rect"], cx, cy):
                why = "frame-changed"
            else:
                why = "spans-cells"
            row["why"] = why
            why_count[why] = why_count.get(why, 0) + 1
            if pick is not None:
                row.update(system=pick["system"], staff=pick["staff"], cell=pick["cell"])
            if why == "frame-changed":
                m_old = by_id.get(old)
                row["master_old_cell_rect"] = m_old["rect"] if m_old else None
                row["label_old_cell_rect"] = [round(float(v), 1) for v in lc["rect"]]
        boxes[b["id"]] = row
    cells = {}
    for c in page["cells"]:
        m = by_id.get(c["id"]) if c["kind"] == "measure" else None
        cells[c["id"]] = {"kind": c["kind"], "master": m["key"] if m else None,
                          "same_rect": bool(m) and [round(float(v)) for v in c["rect"]] == [round(v) for v in m["rect"]]}
    return {
        "schema": SCHEMA,
        "edition": page["edition"], "pdf_page_index": pi, "pdf_name": man["pdf_name"],
        "master": {"version": man["version"], "dir": Path(mdir).name, "dpi": int(man["dpi"]),
                   "pdf_sha256": man["pdf_sha256"], "page_geometry_hash": man["pages"][str(pi)],
                   "built_commit": (man.get("built") or {}).get("commit")},
        "labels": {"file": "data/hand-truth/pages/%s/%d.json" % (page["edition"], pi),
                   "digest": labels_digest(page), "boxes": len(page["boxes"]), "cells": len(page["cells"])},
        "frame": _frame(page, mrows, mcols),
        "summary": {"boxes": len(page["boxes"]), "agree": n_agree, "disagree": len(page["boxes"]) - n_agree,
                    "disagree_by_reason": dict(sorted(why_count.items())),
                    "boxes_with_no_master_cell": sum(1 for v in boxes.values() if v["master"] is None)},
        "cells": cells,
        "boxes": boxes,
    }


def dumps(al: Dict[str, Any]) -> str:
    """Stable text: the sections indented, one line per box and per cell (a 1,500-box page stays readable)."""
    head = {k: v for k, v in al.items() if k not in ("boxes", "cells")}
    out = json.dumps(head, indent=1, sort_keys=True)[:-2]
    for sec in ("cells", "boxes"):
        out += ',\n "%s": {\n' % sec + ",\n".join(
            "  %s: %s" % (json.dumps(k), json.dumps(v, sort_keys=True)) for k, v in sorted(al[sec].items())) + "\n }"
    return out + "\n}\n"


def aligned_path(edition: str, page: int, version: str, aligned_dir: Path = ALIGNED_DIR) -> Path:
    return Path(aligned_dir) / edition / ("%d.%s.json" % (page, version))


# ───────────────────────────── 3. use: what a scorer asks ─────────────────────────────

class Alignment:
    """A loaded aligned file. `cell_of(box_id)` is the master cell of a labelled box; `key_of_label_cell(cell_id)` the
    record key of a label MEASURE cell (the cell with the same id in the master), or None."""

    def __init__(self, data: Dict[str, Any]):
        if data.get("schema") != SCHEMA:
            raise AlignError("aligned file schema %r, this code reads %r" % (data.get("schema"), SCHEMA))
        self.data = data
        self.version = data["master"]["version"]

    @classmethod
    def load(cls, edition: str, page: int, aligned_dir: Path = ALIGNED_DIR, version: Optional[str] = None
             ) -> Optional["Alignment"]:
        d = Path(aligned_dir) / edition
        hits = sorted(d.glob("%d.%s.json" % (page, version or "cm-*"))) if d.is_dir() else []
        if not hits:
            return None
        if len(hits) > 1:
            raise AlignError("%s: several masters aligned (%s); name one" % (d, [h.name for h in hits]))
        return cls(json.loads(hits[0].read_text()))

    def cell_of(self, box_id: str) -> Optional[str]:
        r = self.data["boxes"].get(box_id)
        return r["master"] if r else None

    def key_of_label_cell(self, cell_id: str) -> Optional[Tuple[int, int, int]]:
        """(system, staff-in-system, cell) of the master cell a label measure cell is, for building/reading record keys."""
        c = self.data["cells"].get(cell_id)
        if not c or not c["master"]:
            return None
        _, _p, s, st, n = c["master"].split("/")
        return int(s), int(st), int(n)

    def frame_agrees(self) -> bool:
        f = self.data["frame"]
        m = f["measure_cells"]
        return not (m["rect_changed"] or m["line_ys_changed"] or m["only_in_labels"] or m["only_in_master"]
                    or f["staves"]["only_in_labels"] or f["staves"]["only_in_master"]
                    or f["cell_x_edges_differing_by_system"])

    def summary(self) -> Dict[str, Any]:
        return {"master": self.version, "frame_agrees": self.frame_agrees(), **self.data["summary"]}

    def stale_against(self, page_path: Path) -> Optional[str]:
        """Why this file no longer describes `page_path` (the labels changed), or None."""
        page = json.loads(Path(page_path).read_text())
        if labels_digest(page) != self.data["labels"]["digest"]:
            return "the labels changed since this alignment was made (re-run align)"
        return None


# ───────────────────────────── 4. check ─────────────────────────────

def _diff_rows(old: Dict[str, Any], new: Dict[str, Any]) -> List[str]:
    out = []
    for k in sorted(set(old["boxes"]) | set(new["boxes"])):
        a, b = old["boxes"].get(k), new["boxes"].get(k)
        if a != b:
            out.append("box %s: %s -> %s" % (k, (a or {}).get("master"), (b or {}).get("master")))
    for k in sorted(set(old["cells"]) | set(new["cells"])):
        if old["cells"].get(k) != new["cells"].get(k):
            out.append("cell %s: %s -> %s" % (k, old["cells"].get(k), new["cells"].get(k)))
    if old["frame"] != new["frame"]:
        out.append("frame differs")
    return out


def check(pages_dir: Path = PAGES_DIR, aligned_dir: Path = ALIGNED_DIR, root: Any = None
          ) -> Tuple[bool, List[str], Dict[str, List[str]]]:
    """(ok, messages, moved) over every hand-truth page. A page with a master must have an aligned file that equals a
    fresh derivation byte for byte; a page without one is reported, not failed (nothing to align to).
    `moved[page]` lists the boxes/cells whose master cell moved when an existing file is compared with a fresh one."""
    root = default_root() if root is None else Path(root)
    msgs: List[str] = []
    moved: Dict[str, List[str]] = {}
    ok = True
    for pp in label_pages(pages_dir):
        page = json.loads(pp.read_text())
        pi, ed = int(page["pdf_page_index"]), page["edition"]
        name = "%s:%d" % (ed, pi)
        pdf = (page.get("provenance") or {}).get("pdf")
        mdir = find_master(root, pdf, pi) if pdf else None
        have = sorted((Path(aligned_dir) / ed).glob("%d.cm-*.json" % pi)) if (Path(aligned_dir) / ed).is_dir() else []
        if mdir is None:
            msgs.append("%s: no master cell map for %s page %d under %s (build one: cell_map build PDF --pages %d)"
                        % (name, pdf, pi, root, pi))
            for h in have:                                  # cannot regenerate here; still catch edited labels
                why = Alignment(json.loads(h.read_text())).stale_against(pp)
                if why:
                    ok = False
                    msgs.append("%s: %s STALE: %s" % (name, h.name, why))
            continue
        fresh = build_alignment(pp, mdir)
        want = aligned_path(ed, pi, fresh["master"]["version"], aligned_dir)
        if not want.exists():
            ok = False
            msgs.append("%s: no aligned file %s (run: python3 -m tools.omr.hand_truth.align)" % (name, want.name))
            for h in have:
                prev = json.loads(h.read_text())
                moved[name] = _diff_rows(prev, fresh)
                n_box = sum(1 for k in fresh["boxes"] if (prev["boxes"].get(k) or {}).get("master") != fresh["boxes"][k]["master"])
                msgs.append("%s: %s is for master %s, this master is %s: %d box(es) now fall in a different master cell"
                            % (name, h.name, prev["master"]["version"], fresh["master"]["version"], n_box))
            continue
        if want.read_text() != dumps(fresh):
            ok = False
            moved[name] = _diff_rows(json.loads(want.read_text()), fresh)
            msgs.append("%s: %s is STALE (%d difference(s)); re-run python3 -m tools.omr.hand_truth.align"
                        % (name, want.name, len(moved[name])))
        else:
            s = fresh["summary"]
            msgs.append("%s: aligned to master %s -- %d boxes, %d agree, %d disagree %s" % (
                name, fresh["master"]["version"], s["boxes"], s["agree"], s["disagree"], s["disagree_by_reason"]))
    return ok, msgs, moved


def write_all(pages_dir: Path = PAGES_DIR, aligned_dir: Path = ALIGNED_DIR, root: Any = None) -> List[Path]:
    root = default_root() if root is None else Path(root)
    out = []
    for pp in label_pages(pages_dir):
        page = json.loads(pp.read_text())
        pdf = (page.get("provenance") or {}).get("pdf")
        mdir = find_master(root, pdf, int(page["pdf_page_index"])) if pdf else None
        if mdir is None:
            print("%s:%s -- no master cell map; skipped" % (page["edition"], page["pdf_page_index"]))
            continue
        al = build_alignment(pp, mdir)
        dest = aligned_path(page["edition"], al["pdf_page_index"], al["master"]["version"], aligned_dir)
        dest.parent.mkdir(parents=True, exist_ok=True)
        for old in dest.parent.glob("%d.cm-*.json" % al["pdf_page_index"]):
            if old != dest:
                old.unlink()                                   # one master per page: an older version is superseded
        dest.write_text(dumps(al))
        out.append(dest)
    return out


# ───────────────────────────── 5. the control that can fail ─────────────────────────────

def perturb_barline(src_mdir: Path, dst_root: Path, page: int, *, system: int = 0, x: Optional[int] = None,
                    dx: int = 150) -> Tuple[Path, int]:
    """Copy one master to `dst_root` and move ONE barline column of `page` by `dx` px, everywhere the master spells it:
    the barline rows, the page-wide column, and the x edge of every cell on both sides of it. Returns (new dir, x moved).
    The page's hashes and the manifest version are recomputed so the copy is a well-formed master of other cells."""
    CM = _cm()
    dst = Path(dst_root) / Path(src_mdir).name
    shutil.copytree(src_mdir, dst)
    snap = CM.read_page(dst, page)
    xs = sorted({int(CM.dec(b)["x"]) for b in snap["barlines"] if CM.dec(b)["system_index"] == system})
    inner = [v for v in xs if any(CM.dec(c["v"])["bbox_page_px"][0] == v for c in snap["cells"])]
    if not inner:
        raise AlignError("no inner barline on page %d system %d" % (page, system))
    x = inner[len(inner) // 2] if x is None else x

    def shift(v: Any) -> Any:
        return v + dx if isinstance(v, (int, float)) and int(v) == x else v

    def edit(enc_obj: Any) -> Any:
        return CM.enc(_apply(CM.dec(enc_obj)))

    def _apply(o: Dict[str, Any]) -> Dict[str, Any]:
        if "x" in o and o.get("system_index") == system:
            o["x"] = shift(o["x"])
        if "bbox_page_px" in o and o.get("system_index") == system:
            b = list(o["bbox_page_px"])
            b[0], b[2] = shift(b[0]), shift(b[2])
            o["bbox_page_px"] = tuple(b)
        return o

    snap["barlines"] = [edit(b) for b in snap["barlines"]]
    for c in snap["cells"]:
        c["v"] = edit(c["v"])
    pws = CM.dec(snap["pws"])
    for col in ((pws.get("system_structure") or {}).get(system) or {}).get("columns", []):
        col["x"] = shift(col["x"])
    snap["pws"] = CM.enc(pws)
    snap["geometry_hash"] = CM.geometry_hash(snap)
    CM._page_file(dst, page).write_bytes(CM.gzip.compress(CM._canon(snap), 6))
    man = json.loads((dst / "manifest.json").read_text())
    man["pages"][str(page)] = snap["geometry_hash"]
    man["version"] = CM.version_tag(man["pdf_sha256"], int(man["dpi"]), man["pages"])
    (dst / "manifest.json").write_text(json.dumps(man, indent=1, sort_keys=True) + "\n")
    return dst, x


def control(pages_dir: Path = PAGES_DIR, aligned_dir: Path = ALIGNED_DIR, root: Any = None, dx: int = 150
            ) -> Tuple[bool, List[str]]:
    """Run `check` against a master with one barline moved. PASSES (True) when the check FAILS and names the moved
    boxes; a check that stayed green would be a check that cannot fail (CLAUDE rule 7)."""
    root = default_root() if root is None else Path(root)
    lines: List[str] = []
    done = False
    with tempfile.TemporaryDirectory() as td:
        for pp in label_pages(pages_dir):
            page = json.loads(pp.read_text())
            pdf = (page.get("provenance") or {}).get("pdf")
            mdir = find_master(root, pdf, int(page["pdf_page_index"])) if pdf else None
            if mdir is None:
                continue
            base = build_alignment(pp, mdir)
            # move the inner barline with the most labelled boxes just to its right, so the control has boxes to move
            mrows = _master_cells(mdir, base["pdf_page_index"])[1]
            x_min = min(q["rect"][0] for q in mrows)
            best = None
            for xv in sorted({int(r["rect"][0]) for r in mrows if r["rect"][0] > x_min}):
                n = sum(1 for b in page["boxes"] if xv <= (b["rect"][0] + b["rect"][2]) / 2.0 < xv + dx)
                if best is None or n > best[0]:
                    best = (n, xv)
            if best is None:
                continue
            xv = best[1]
            pdir, xm = perturb_barline(mdir, Path(td) / "moved", base["pdf_page_index"], x=xv, dx=dx)
            moved_al = build_alignment(pp, pdir)
            n = sum(1 for k, v in moved_al["boxes"].items() if v["master"] != base["boxes"][k]["master"])
            ok, msgs, moved = check(pages_dir, aligned_dir=aligned_dir, root=pdir.parent)
            lines.append("%s:%d  master %s -> %s with the barline at x=%d moved %+d px"
                         % (base["edition"], base["pdf_page_index"], base["master"]["version"],
                            moved_al["master"]["version"], xv, dx))
            lines.append("  boxes whose master cell changed: %d; label cells whose rectangle no longer matches the "
                         "master: %d" % (n, len(moved_al["frame"]["measure_cells"]["rect_changed"])))
            for k, v in sorted(moved_al["boxes"].items()):
                if v["master"] != base["boxes"][k]["master"]:
                    lines.append("    %s (%s): %s -> %s" % (k, v["old"], base["boxes"][k]["master"], v["master"]))
                    if sum(1 for ln in lines if ln.startswith("    ")) >= 12:
                        lines.append("    ...")
                        break
            lines.append("  `check` on the perturbed master: %s" % ("FAILED (as it must)" if not ok else "PASSED -- the check cannot fail"))
            lines.extend("    " + m for m in msgs)
            done = True
            if ok:
                return False, lines
    if not done:
        lines.append("no hand-truth page has a master here; the control did not run")
    return done, lines


# ───────────────────────────── 6. the command ─────────────────────────────

def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if an aligned file is stale or missing")
    ap.add_argument("--report", action="store_true", help="print every box whose old cell id disagrees with the master")
    ap.add_argument("--control", action="store_true", help="move one master barline in a temp copy; the check must fail")
    ap.add_argument("--root", default=None, help="cell-maps root (default: the library's)")
    a = ap.parse_args(list(argv) if argv is not None else None)
    if a.control:
        ok, lines = control(root=a.root)
        print("\n".join(lines))
        return 0 if ok else 1
    if a.report:
        root = default_root() if a.root is None else Path(a.root)
        for pp in label_pages():
            page = json.loads(pp.read_text())
            mdir = find_master(root, (page.get("provenance") or {}).get("pdf"), int(page["pdf_page_index"]))
            if mdir is None:
                print("%s:%s no master" % (page["edition"], page["pdf_page_index"]))
                continue
            al = build_alignment(pp, mdir)
            print("%s:%d master %s  frame: %s" % (al["edition"], al["pdf_page_index"], al["master"]["version"],
                                                 json.dumps(al["frame"]["measure_cells"] | {"rect_changed": len(
                                                     al["frame"]["measure_cells"]["rect_changed"])}, sort_keys=True)))
            print("  " + json.dumps(al["summary"], sort_keys=True))
            for k, v in sorted(al["boxes"].items()):
                if not v["ok"]:
                    print("  %-7s %-14s -> %-16s %s" % (k, v["old"], v["master_id"], v["why"]))
        return 0
    if a.check:
        ok, msgs, _ = check(root=a.root)
        print("\n".join(msgs))
        return 0 if ok else 1
    root = a.root
    for dest in write_all(root=root):
        print("wrote", dest.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
