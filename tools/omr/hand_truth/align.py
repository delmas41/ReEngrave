"""Hand truth aligned to the MASTER CELL MAP (ROADMAP 2.231 follow-up; Sean 2026-10-30).

    python3 -m tools.omr.hand_truth.align                 # write data/hand-truth/aligned/<edition>/<page>.<master>.json
    python3 -m tools.omr.hand_truth.align --check         # exit 1 if any aligned file is stale or missing
    python3 -m tools.omr.hand_truth.align --report        # print the disagreements, box by box
    python3 -m tools.omr.hand_truth.align --control       # move one master barline in a temp copy; the check must fail

Sean's labels sit on `data/hand-truth/pages/<edition>/<page>.json`: every box has a PAGE-pixel rect (robust) and a
`cell_id` (`s0-st9-m2`) -- the cell it was labelled through, cut by whatever tree the labelling session ran on. The
master cell map (`staged/cell_map.py`) freezes the cells a gather reads. This file is the DERIVED bridge between them:
for each box, the master cell (page, system, staff-in-system, cell) that holds it, found BY PAGE RECT, never by the old
id. Sean's page files are not touched; this file is regenerated by one command and `--check` fails the moment the
labels, the master or this code move.

HOW A BOX FINDS ITS MASTER CELL. The master cell (`bbox_page_px`, x0 <= cx < x1, y0 <= cy < y1) that holds the box's
centre. Neighbouring staves' cells overlap vertically (their pads), so a centre can lie in two: the box takes the one
whose id it was labelled in when that cell holds it too (both hold it -- nothing is chosen), else the cell whose staff
middle line is nearest. A centre in no master cell has no master cell (None): the master holds MEASURE cells only.

WHY AN OLD `cell_id` AND ITS MASTER CELL DISAGREE (`reason`):
  label-only-cell   the box was labelled through a `margin-N` / `top-N` / `bottom-N` cell (the session cuts those for
                    ink outside every bar; the master never has them). Its master cell is the measure cell holding it,
                    or None when the ink is outside every bar (system names, titles, page numbers).
  frame-changed     the label's own cell still holds the box's centre but the master cell with that id has another
                    rectangle (a barline the page-wide pass added/removed/moved, a staff re-cut) or is gone.
  spans-cells       the box's centre is in ANOTHER measure cell than the one it was drawn in, and the label's own
                    rectangle for that cell already says so (a barline or brace crossing staves, a tie over a
                    barline): the old and the master frame agree and the id is just the cell it was filed under.

A DERIVED file: no timestamp, byte-identical on two runs of one tree (`--check` can fail).
"""
from __future__ import annotations

