"""How many meter-change fixtures does this repo ALREADY hold, and of which shape?

⚠️ WHY THIS EXISTS. Every meter finding in this project is blocked on the same
sentence: *"n = 1 piece of music"*. The cautionary arbiter, the corroboration
guard, the `OMR_METER_CARRY` flip and the "designed limit" observation all end
by asking for a second document, and each names ONE candidate by hand.

Nobody counted the pool. It is not 1.

⚠️ IT NEEDS NO `library/` AND NO WEIGHTS. `data/dossiers/*.json` are COMMITTED,
generated by `tools.omr.training.build_dossiers` from the reference MusicXML,
and carry `meter_changes` per work. So the truth about which works change meter,
where, and to what is answerable in a cloud container — which
`docs/cloud-session-capabilities-2026-09-09.md` does not record.

⚠️ THE SHAPE SPLIT IS THE RESULT, NOT THE COUNT. A change that alters the BAR
LENGTH can be arbitrated by bar sums; one that does not, cannot -- structurally,
not by degradation. `report_boundary.length_of` already encodes that a `C` and a
`C|` are both 4.0 quarter notes, and its own comment records that the line was
WRONG until a fixture made it matter. So the pool is split by that predicate
rather than by the spelling.

⚠️ AND A THIRD CLASS FALLS OUT THAT IS NOT A CHANGE AT ALL: a `<time>` restated
IDENTICALLY (`2/4 -> 2/4`). Those are the population `_meter_changes`' own
"against the meter IN FORCE" rule exists to suppress -- *"a system does not
change meter five times to the meter it is already in"* -- so they are reported
apart and must never be counted as fixtures for the engraving shape.

    python3 benchmarks/omr-meter-fixture-pool-2026-09/probe_fixture_pool.py
    python3 benchmarks/omr-meter-fixture-pool-2026-09/probe_fixture_pool.py --check

`--check` exits non-zero when the instrument is DEAD (no dossiers readable, or
no meter_changes field anywhere) -- never on a threshold. A pool count used as a
gate would be gamed by adding dossiers.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DOSSIERS = ROOT / "data" / "dossiers"


def quarter_length(beats: int, beat_type: int) -> float:
    """A meter's bar length in quarter notes. `C` and `C|` are BOTH 4.0."""
    return beats * 4.0 / beat_type


def classify(dossier: dict):
    """Walk a work's meter_changes in order, tracking the meter IN FORCE.

    Returns (length_changes, engraving_changes, identical_restatements), each a
    list of (measure, before, after, ql_before, ql_after).
    """
    changes = dossier.get("meter_changes") or []
    length, engraving, identical = [], [], []
    in_force = None
    for m in changes:
        measure = m.get("measure", 1)
        if in_force is not None and measure > 1:
            a = quarter_length(in_force["beats"], in_force["beat_type"])
            b = quarter_length(m["beats"], m["beat_type"])
            before = f"{in_force['beats']}/{in_force['beat_type']}"
            after = f"{m['beats']}/{m['beat_type']}"
            row = (measure, before, after, a, b)
            if abs(a - b) > 1e-9:
                length.append(row)
            elif before == after:
                identical.append(row)
            else:
                engraving.append(row)
        in_force = m
    return length, engraving, identical


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()

    files = sorted(DOSSIERS.glob("*.json"))
    works, read, with_field = {}, 0, 0
    for f in files:
        try:
            j = json.load(open(f))
        except Exception:
            continue
        read += 1
        if j.get("meter_changes") is not None:
            with_field += 1
        works[f.stem] = classify(j)

    n_length = sum(len(v[0]) for v in works.values())
    n_engrave = sum(len(v[1]) for v in works.values())
    n_ident = sum(len(v[2]) for v in works.values())
    changing_works = sorted(k for k, v in works.items() if v[0] or v[1])
    engrave_works = sorted(k for k, v in works.items() if v[1])

    print(f"REACH  committed dossiers {len(files)}  readable {read}  "
          f"carrying a meter_changes field {with_field}")
    print()
    print(f"  works with ANY real mid-movement change ...... {len(changing_works)}")
    print(f"  changes that ALTER the bar length ............ {n_length}")
    print(f"  changes at CONSTANT length (engraving only) .. {n_engrave}"
          f"   across {len(engrave_works)} works")
    print(f"  identical restatements (NOT a change) ........ {n_ident}")
    print()
    print("THE ENGRAVING SHAPE — bar sums are structurally SILENT on these,")
    print("so they are the fixtures for the 'designed limit' question:")
    for stem in engrave_works:
        for measure, before, after, q, _ in works[stem][1]:
            print(f"  {stem:30s} m{measure:<6} {before:>5} -> {after:<5} (both {q} ql)")

    if a.json:
        out = ROOT / "benchmarks/omr-meter-fixture-pool-2026-09/out/fixture-pool.json"
        out.write_text(json.dumps(
            {"dossiers": len(files), "readable": read, "with_field": with_field,
             "length_changes": n_length, "engraving_changes": n_engrave,
             "identical_restatements": n_ident,
             "works": {k: {"length": v[0], "engraving": v[1], "identical": v[2]}
                       for k, v in works.items() if v[0] or v[1] or v[2]}},
            indent=2))
        print(f"\nwrote {out}")

    if a.check:
        if read == 0:
            print("\nDEAD: no dossier was readable — this instrument measured nothing.")
            return 3
        if with_field == 0:
            print("\nDEAD: not one dossier carries a meter_changes field.")
            return 3
        print("\nCHECK OK — the instrument read something and can tell the shapes apart.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
