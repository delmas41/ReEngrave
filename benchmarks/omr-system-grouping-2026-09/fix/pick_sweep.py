"""Pick ~15 clean instrumental MULTI-system sweep pages as extra controls.

Presumed-correct criterion: an orchestral page whose systems are EQUAL-sized
(or differ by <=1) with NO lone-staff system is almost certainly grouped right —
a symphony has constant instrumentation, so N stacked systems of the full
ensemble read as N equal blocks. We deliberately spread across works/publishers.
We also add a few large single-system dense pages (grouping trivial) as negative
controls that the detector must not split.

Writes sweep_controls.py: SWEEP_CONTROLS = [(cid, pdf_rel, page, dpi, exp_sys), ...]
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

SWEEP = (Path(__file__).parent.parent / "sweep.jsonl").resolve()
LIB = Path("/Users/seanjohnson/Desktop/ReEngrave/library/editions")


def load_rows():
    rows = []
    with open(SWEEP) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            if r.get("error") or not r.get("staves_per_system"):
                continue
            rows.append(r)
    return rows


def is_clean_multisystem(r):
    sps = r["staves_per_system"]
    if len(sps) < 2:
        return False
    if min(sps) == 1:            # any lone-staff system -> not clean
        return False
    if max(sps) - min(sps) > 1:  # systems must be near-equal (constant ensemble)
        return False
    if r["n_staves"] < 8:        # orchestral scale
        return False
    if r["n_staves"] // len(sps) < 4:
        return False
    return True


def is_dense_single(r):
    sps = r["staves_per_system"]
    return len(sps) == 1 and r["n_staves"] >= 14


def work_of(pdf_rel):
    # library/editions/<composer>/<work>/<file>
    parts = Path(pdf_rel).parts
    return "/".join(parts[:2]) if len(parts) >= 2 else pdf_rel


def main():
    rows = load_rows()
    multis = [r for r in rows if is_clean_multisystem(r)]
    singles = [r for r in rows if is_dense_single(r)]

    # Spread multi-system picks across distinct works; prefer the most-equal,
    # most-systems pages.
    by_work = defaultdict(list)
    for r in multis:
        by_work[work_of(r["pdf_rel"])].append(r)

    picked = []
    seen_works = set()
    # one page per work, most systems first, then most staves
    for work, rs in sorted(by_work.items()):
        rs.sort(key=lambda r: (len(r["staves_per_system"]), r["n_staves"]), reverse=True)
        r = rs[0]
        picked.append(r)
        seen_works.add(work)
        if len(picked) >= 12:
            break

    # a few dense single-system pages from distinct works not already picked
    dense_pick = []
    by_work_s = defaultdict(list)
    for r in singles:
        by_work_s[work_of(r["pdf_rel"])].append(r)
    for work, rs in sorted(by_work_s.items()):
        if work in seen_works:
            continue
        rs.sort(key=lambda r: r["n_staves"], reverse=True)
        dense_pick.append(rs[0])
        seen_works.add(work)
        if len(dense_pick) >= 4:
            break

    allrows = picked + dense_pick

    out_lines = ["# Auto-generated by pick_sweep.py — clean instrumental controls.",
                 "# (cid, pdf_rel, page, dpi, expected_systems). expected = current",
                 "# rule's grouping, presumed correct (equal-size stacked systems / dense single).",
                 "SWEEP_CONTROLS = ["]
    print(f"{'cid':22s} {'sys':>10s} {'staves':>6} {'dpi':>4}  publisher")
    used_cids = set()
    for r in allrows:
        stem = Path(r["pdf_rel"]).stem
        # short cid: composer-workabbr-pXX
        parts = Path(r["pdf_rel"]).parts
        comp = parts[0][:4]
        work = parts[1].split("-")[0][:6] if len(parts) > 1 else "x"
        cid = f"sw-{comp}-{work}-p{r['page']}"
        n = 2
        base = cid
        while cid in used_cids:
            cid = f"{base}_{n}"; n += 1
        used_cids.add(cid)
        exp = len(r["staves_per_system"])
        out_lines.append(f'    ({cid!r}, {r["pdf_rel"]!r}, {r["page"]}, {r["dpi"]}, {exp}),')
        print(f"{cid:22s} {str(r['staves_per_system']):>10s} {r['n_staves']:>6} "
              f"{r['dpi']:>4}  {r.get('publisher','?')}")
    out_lines.append("]")
    (Path(__file__).with_name("sweep_controls.py")).write_text("\n".join(out_lines) + "\n")
    print(f"\nwrote {len(allrows)} controls -> sweep_controls.py")


if __name__ == "__main__":
    main()
